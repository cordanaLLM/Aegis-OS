/// Negative: tellus fields and statics; see [`surface_scan::assert_reads_fields_and_statics`].
#[test]
fn the_scanner_reads_public_fields_and_statics_and_not_private_ones() {
    surface_scan::assert_reads_fields_and_statics(
        &[
            ("pub untested_knob: u8,", "untested_knob"),
            (
                "pub static UNTESTED_REGISTER: StoreState = StoreState::Uninitialised;",
                "UNTESTED_REGISTER",
            ),
            ("pub zone: RaplZone,", "zone"),
            ("pub provenance: Provenance,", "provenance"),
            ("pub functional_units: f64,", "functional_units"),
            ("pub const fn tag(self) -> u8 {", "tag"),
        ],
        &[
            "zones: [Option<RaplZone>; MAX_RAPL_ZONES],",
            "pub(crate) fn decode_text<T>(schema: SchemaId, text: &str) -> Result<T, ContractError> {",
            "pub use crate::sci::SciEngine;",
            "pub mod contracts;",
            "let pub_like = 1;",
            "",
        ],
    );
}

// --- Boundary -------------------------------------------------------------

/// Boundary: tellus identifier matching; see [`surface_scan::assert_identifier_matcher_is_exact`].
#[test]
fn the_identifier_matcher_is_exact_at_both_ends() {
    surface_scan::assert_identifier_matcher_is_exact(
        &[
            ("TellusError::ZoneAbsent", "ZoneAbsent"),
            ("ZoneList", "ZoneList"),
        ],
        &[
            ("MAX_CGROUP_SLICES", "CGROUP_SLICES"),
            ("sci_rate_of", "sci_rate"),
            ("outer_ZoneList", "ZoneList"),
            ("ZoneList2", "ZoneList"),
            ("", "ZoneList"),
        ],
    );
}

/// Boundary: tellus field arm floor; see [`surface_scan::assert_field_arm_carries_the_floor`].
#[test]
fn the_field_arm_carries_the_floor() {
    surface_scan::assert_field_arm_carries_the_floor(
        env!("CARGO_MANIFEST_DIR"),
        FIELD_ARM_NAMES,
        MINIMUM_SURFACE,
    );
}
