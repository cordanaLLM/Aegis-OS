//! The generalised public-surface sweep, carried over from
//! `aegis-janus-lifecycle` and `aegis-hestia`.
//!
//! HISS-15 asks for positive, negative and boundary coverage of every public
//! interface. Reviewing that by hand caught individual holes and then let new
//! ones in, so the sweep is mechanised here instead of repeated by eye.
//!
//! The rule is deliberately crude and therefore checkable: every name the
//! crate's `src/` declares as public API -- a type, an enum variant, a method,
//! a trait item, an associated or free constant, a public struct field, a
//! public static -- must appear as a whole identifier in at least one
//! integration test. A public item with no test reference is either untested
//! surface or surface that should not exist; both are findings, and this file
//! turns either into a failed gate.
//!
//! Public struct fields and statics are on that list because the M15
//! verification found them off it: a sweep that only understood
//! keyword-introduced items passed over a planted `pub untested_knob: u8` and
//! a planted `pub static UNTESTED_REGISTER`. This crate carries several
//! all-public-field types -- every payload, every sample and every recorded
//! claim -- so the field arm carries more weight here, not less.
//!
//! The same reasoning is why this crate's identifiers are written out rather
//! than generated by a macro: a macro-generated `pub struct` is surface this
//! sweep cannot see, which is the same hole in a different shape.
//!
//! What the rule does not claim: a name that appears is not thereby proved
//! correct. The triples that exercise these items live in this crate's other
//! test files. This sweep only guarantees that none of them is forgotten.
//!
//! This file excludes itself from the scanned test sources. A sweep that could
//! read its own expectation list would pass by naming the names it checks.

/// This file's name, excluded from the scanned test sources.
const SWEEP_FILE: &str = "public_surface.rs";

/// The smallest public surface the scanner may report before it is assumed to
/// be reading nothing rather than finding nothing.
///
/// The figure is measured, not guessed: 180 names are collected from this
/// crate's `src/` on 2026-09-13, of which [`FIELD_ARM_NAMES`] come from the
/// public-field and `pub static` arm of [`declared_name`] that the M15
/// verification found missing. The floor sits eight below the total so that
/// removing one item on purpose does not fail the gate, while dropping the
/// field arm -- which costs sixteen -- does. Removing public surface on
/// purpose means lowering the floor on purpose. M21 (2026-09-29) added the
/// measured-energy module: the walk collects 215 names, 195 of them without
/// the field arm, so the floor moves to 207, eight below the total and above
/// what a keyword-only sweep collects.
const MINIMUM_SURFACE: usize = 207;

/// How many of the collected names only the M15 arm reads.
///
/// Measured on 2026-09-13 by running the same walk twice: 180 names with the
/// arm and 164 without it. `the_field_arm_carries_the_floor` asserts the
/// difference, so the figure cannot drift out of agreement with the code the
/// way a number stated only in prose can. Every one of the 16 is a public
/// struct field; this crate declares no `pub static`, so that half of the arm
/// is coverage for a shape this `src/` does not yet use. M16 (2026-09-29)
/// added `CarbonTelemetry`, whose `power_watts` and `grid_intensity` are the
/// two field names no other struct already declared, so the arm reads 18.
/// M21 added `CounterPair`, whose `before` and `after` are new the same way;
/// its `interval` is not, so the arm reads 20.
const FIELD_ARM_NAMES: usize = 20;

#[path = "../../surface_scan.rs"]
mod surface_scan;

// --- Positive -------------------------------------------------------------

/// Positive: tellus public surface; see [`surface_scan::assert_every_public_item_is_named`].
#[test]
fn every_public_item_is_named_by_an_integration_test() {
    surface_scan::assert_every_public_item_is_named(
        env!("CARGO_MANIFEST_DIR"),
        SWEEP_FILE,
        MINIMUM_SURFACE,
    );
}

